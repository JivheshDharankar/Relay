  PAYMENT_DECLINED = 'PAYMENT_DECLINED',
  PAYMENT_INSUFFICIENT_FUNDS = 'PAYMENT_INSUFFICIENT_FUNDS',
  MANDATE_LIMIT_EXCEEDED = 'MANDATE_LIMIT_EXCEEDED',
  DUPLICATE_PAYMENT_SUBMIT = 'DUPLICATE_PAYMENT_SUBMIT',

